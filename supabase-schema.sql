-- =========================================================
-- SME EXPENSE & ORDER APP - SUPABASE DATABASE SCHEMA
-- =========================================================

-- 1. สร้างตารางคำสั่งซื้อ (Orders)
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_date DATE NOT NULL DEFAULT CURRENT_DATE,
    order_id TEXT NOT NULL UNIQUE,
    customer_name TEXT NOT NULL,
    phone TEXT DEFAULT '',
    address TEXT DEFAULT '',
    delivery_method TEXT DEFAULT 'รถกระบะร้าน',
    delivery_date DATE,
    product_details TEXT DEFAULT '',
    total_price NUMERIC(12, 2) NOT NULL DEFAULT 0,
    deposit NUMERIC(12, 2) NOT NULL DEFAULT 0,
    balance NUMERIC(12, 2) NOT NULL DEFAULT 0,
    order_status TEXT DEFAULT 'มัดจำแล้ว',
    payment_status TEXT NOT NULL DEFAULT 'มัดจำแล้ว',
    prod_status TEXT NOT NULL DEFAULT 'รอดำเนินการ',
    delivery_status TEXT NOT NULL DEFAULT 'รอจัดส่ง',
    note TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. สร้างตารางบันทึกค่าใช้จ่าย (Expenses)
CREATE TABLE IF NOT EXISTS public.expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_date DATE NOT NULL DEFAULT CURRENT_DATE,
    month TEXT NOT NULL,
    bill_no TEXT DEFAULT '',
    vendor TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT 'เบ็ดเตล็ด/อื่นๆ',
    item_name TEXT NOT NULL,
    qty NUMERIC(10, 2) NOT NULL DEFAULT 1,
    unit TEXT DEFAULT 'ชิ้น',
    unit_price NUMERIC(12, 2) NOT NULL DEFAULT 0,
    total_item_price NUMERIC(12, 2) NOT NULL DEFAULT 0,
    payment_method TEXT NOT NULL DEFAULT 'โอนเงิน',
    file_url TEXT DEFAULT '',
    note TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 3. เปิดการใช้งาน Row Level Security (RLS)
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.expenses ENABLE ROW LEVEL SECURITY;

-- 4. ตั้งค่า Policy ให้อนุญาตอ่านและเขียนข้อมูล (Public / Anon access)
DROP POLICY IF EXISTS "Allow public read access on orders" ON public.orders;
CREATE POLICY "Allow public read access on orders" 
ON public.orders FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow public insert access on orders" ON public.orders;
CREATE POLICY "Allow public insert access on orders" 
ON public.orders FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public update access on orders" ON public.orders;
CREATE POLICY "Allow public update access on orders" 
ON public.orders FOR UPDATE USING (true);

DROP POLICY IF EXISTS "Allow public delete access on orders" ON public.orders;
CREATE POLICY "Allow public delete access on orders" 
ON public.orders FOR DELETE USING (true);

DROP POLICY IF EXISTS "Allow public read access on expenses" ON public.expenses;
CREATE POLICY "Allow public read access on expenses" 
ON public.expenses FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow public insert access on expenses" ON public.expenses;
CREATE POLICY "Allow public insert access on expenses" 
ON public.expenses FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public update access on expenses" ON public.expenses;
CREATE POLICY "Allow public update access on expenses" 
ON public.expenses FOR UPDATE USING (true);

DROP POLICY IF EXISTS "Allow public delete access on expenses" ON public.expenses;
CREATE POLICY "Allow public delete access on expenses" 
ON public.expenses FOR DELETE USING (true);

-- 5. สร้าง Storage Bucket สำหรับเก็บรูปบิล (Receipts)
INSERT INTO storage.buckets (id, name, public) 
VALUES ('receipts', 'receipts', true)
ON CONFLICT (id) DO NOTHING;

-- 6. นโยบายให้ทุกคนสามารถดูและอัปโหลดรูปบิลได้
DROP POLICY IF EXISTS "Allow public read receipts" ON storage.objects;
CREATE POLICY "Allow public read receipts" 
ON storage.objects FOR SELECT 
USING (bucket_id = 'receipts');

DROP POLICY IF EXISTS "Allow public upload receipts" ON storage.objects;
CREATE POLICY "Allow public upload receipts" 
ON storage.objects FOR INSERT 
WITH CHECK (bucket_id = 'receipts');

-- 7. อัปเกรดคอลัมน์ order_status สำหรับตารางคำสั่งซื้อเดิม (Migration)
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS order_status TEXT DEFAULT 'มัดจำแล้ว';
